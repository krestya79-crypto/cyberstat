const normal = (mu: number, sd: number, a: number, tail = 'left', b?: number): Values => ({
  mu: String(mu),
  sd: String(sd),
  a: String(a),
  b: String(b ?? a + 1),
  tail,
  normal: 'true',
});
const mean = (mu: number, sd: number, n: number, a: number, tail = 'left', b?: number): Values => ({
  ...normal(mu, sd, a, tail, b),
  n: String(n),
});
const prop = (p: number, n: number, a?: number, tail = 'left', b?: number): Values => ({
  p: String(p),
  n: String(n),
  a: String(a ?? p),
  b: String(b ?? p + 0.1),
  tail,
});
const ci = (xbar: number, sd: number, n: number): Values => ({
  xbar: String(xbar),
  sd: String(sd),
  n: String(n),
  confidence: '95',
  normal: 'true',
});
